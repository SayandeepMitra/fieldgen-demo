"""Table build (generic; generator side): one query per target table from the recipe and the final formulas, run on the source data, stored in one DuckDB file.
A column without a formula is NULL of its target type; columns generated by the recipe (keys) are numbered over the combined rows."""
import re
import duckdb
from fieldgen.assemble import assemble_table

def table_query(recipe, columns, exprs, types):
    """assemble_table with several generated keys numbered one after the other (a key may be ordered by an earlier generated key)."""
    gen = {k["column"]: k for k in recipe.get("keys") or [] if k["column"] in columns}
    if len(gen) < 2: return assemble_table(recipe, columns, exprs, types)
    first = next(iter(gen)); one = dict(recipe); one["keys"] = [k for k in recipe["keys"] if k["column"] == first]
    q = assemble_table(one, columns, exprs, types)
    for c, k in list(gen.items())[1:]: q = f'SELECT *, CAST(ROW_NUMBER() OVER (ORDER BY {", ".join(k["order_by"])}) AS {types[c]}) AS "{c}" FROM ({q})'
    return q

def _try(con, q):
    try: return True, con.execute(f"select count(*) from ({q})").fetchone()[0], None
    except Exception as e: return False, None, str(e)[:200]

def build_tables(con, db_path, tables):
    """tables: [{table, recipe, columns, types, exprs}] -> [{table, ok, rows, error, dropped_window_formulas, sql}]. Writes the tables into the DuckDB file db_path."""
    con.execute(f"ATTACH '{db_path}' AS built"); out = []
    for t in tables:
        q = table_query(t["recipe"], t["columns"], t["exprs"], t["types"]); ok, n, err = _try(con, q); dropped = []
        if not ok and "nested" in (err or "").lower():     # a window formula under a generated-key window: build without those formulas
            keep = {c: e for c, e in t["exprs"].items() if not any(re.search(r"\bover\s*\(", s, re.I) for s in e.values())}
            dropped = sorted(set(t["exprs"]) - set(keep)); q = table_query(t["recipe"], t["columns"], keep, t["types"]); ok, n, err = _try(con, q)
        if ok: con.execute(f'CREATE OR REPLACE TABLE built."{t["table"]}" AS {q}')
        out.append({"table": t["table"], "ok": ok, "rows": n, "error": err, "dropped_window_formulas": dropped, "sql": q})
    con.execute("DETACH built"); return out
