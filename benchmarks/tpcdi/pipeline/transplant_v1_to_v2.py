"""Reuse model answers whose PROMPT SCOPE did not change between the v1 and v2 gold.

A model answer depends on its prompt. Everything above "SAMPLE DATA" in the prompt (target column, query scope, visible relations,
matched fields, conventions) is derived from the gold SQL; the sample rows / profile below it are DuckDB tie-order noise. For every
(table.column) whose pre-"SAMPLE DATA" text is identical in the v1 run and in the freshly built v2 prompts, the v1 answers (every model
and repeat) are copied into runs/v2/RUN/results.jsonl unchanged (they are then GRADED against the v2 gold like any other answer).
Columns whose scope changed get no answers here: they are regenerated by run_v4.py under TPCDI_GOLD=v2.

usage: python transplant_v1_to_v2.py RUN [--v2-prompts runs/v2/OTHER/prompts.json]
Writes runs/v2/RUN/results.jsonl (+ transplant_report.json). Never touches the v1 run.
"""
import argparse, json, os, collections
HERE = os.path.dirname(os.path.abspath(__file__))

ap = argparse.ArgumentParser(); ap.add_argument("run"); ap.add_argument("--v2-prompts", default=None); a = ap.parse_args()
v1_dir, v2_dir = os.path.join(HERE, "runs", a.run), os.path.join(HERE, "runs", "v2", a.run)
os.makedirs(v2_dir, exist_ok=True)
p1 = json.load(open(os.path.join(v1_dir, "prompts.json")))
p2 = json.load(open(a.v2_prompts or os.path.join(v2_dir, "prompts.json")))
if not os.path.exists(os.path.join(v2_dir, "prompts.json")):
    json.dump(p2, open(os.path.join(v2_dir, "prompts.json"), "w"))
sig = lambda p: p.split("\nSAMPLE DATA")[0] if p else None
keys = [k for k in p2 if not k.startswith("_")]
same = {k for k in keys if p1.get(k) and p2.get(k) and sig(p1[k]) == sig(p2[k])}
out = os.path.join(v2_dir, "results.jsonl")
have = set()
if os.path.exists(out):
    for l in open(out):
        r = json.loads(l); have.add((r["key"], r["model"], r["repeat"]))
n = 0
with open(out, "a") as fh:
    for l in open(os.path.join(v1_dir, "results.jsonl")):
        r = json.loads(l)
        if r["key"] in same and not r.get("error") and (r["key"], r["model"], r["repeat"]) not in have:
            r["transplanted_from"] = "v1"
            fh.write(json.dumps(r) + "\n"); n += 1
rep = {"run": a.run, "columns": len(keys), "scope_unchanged": len(same), "scope_changed": len(keys) - len(same),
       "records_copied": n, "changed_keys": sorted(set(keys) - same)}
json.dump(rep, open(os.path.join(v2_dir, "transplant_report.json"), "w"), indent=1)
print(f"{a.run}: {len(same)}/{len(keys)} columns keep their v1 answers ({n} records copied); {len(keys)-len(same)} to regenerate")
